//! RAFF relaxation benchmark (Q2b) — position-based vs force-based solvers.
//!
//! Theory doc §11.8: three distortion types (D1 random, D2 stretch, D3a dihedral)
//! × two convergence targets (T1 accurate, T2 rough/interactive).
//!
//! Per solver × distortion × molecule, reports:
//!   - Convergence curve: residual RMSD (log) vs macrostep  → CSV
//!   - Force curve: max|F| (log) vs macrostep               → CSV
//!   - Steps-to-T2 (rough: RMSD<0.05Å or |F|<0.1 eV/Å)
//!   - Steps-to-T1 (accurate: |F|<1e-3 eV/Å = 1 meV/Å)
//!   - N_soft (port-force evals), t_wall (single-thread µs)
//!
//! CSVs written to debug/raff_bench/. Plots generated by plot_raff_bench.py.
//!
//! Run:  cargo run --release -p molff --bin raff_bench
//! Then: python3 debug/raff_bench/plot_raff_bench.py

