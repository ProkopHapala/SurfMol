/// Relax with a position-based solver, tracking per-step max|F| (primary) + RMSD vs reference (secondary).
/// Supports both legacy projection-only mode (pd_inertia=false) and proper PD (pd_inertia=true + vel_reset).
fn trace_pos(init: &RaffState, ref_pos: &[Vec3d], topo: &RaffTopology, solver: PosSolver, dt: f64, iters: usize, over_relax: f64, max_macro: usize) -> Trace {
    trace_pos_ext(init, ref_pos, topo, solver, dt, iters, over_relax, max_macro, OrientMode::Adiabatic, false, false, 0.0, 0.0, 0, 0)
}

/// Extended trace_pos with orientation mode, PD inertia, and heavy-ball momentum params.
fn trace_pos_ext(init: &RaffState, ref_pos: &[Vec3d], topo: &RaffTopology, solver: PosSolver, dt: f64, iters: usize, over_relax: f64, max_macro: usize,
    orient_mode: OrientMode, pd_inertia: bool, vel_reset: bool, bmix_start: f64, bmix_end: f64, bmix_istart: usize, bmix_iend: usize) -> Trace {
    let mut s = init.clone();
    if orient_mode == OrientMode::Adiabatic { solve_all_rotations(&mut s, topo); }
    let cfg = RaffConfig { orient_mode, dyn_mode: DynMode::Xpbd,
        pos_solver: solver, dt, cdamp: if pd_inertia { 1.0 } else { 0.0 }, rot_damp: if pd_inertia { 1.0 } else { 0.0 }, flim: 0.0,
        xpbd_iters: iters, xpbd_over_relax: over_relax,
        pd_inertia, vel_reset, bmix_start, bmix_end, bmix_istart, bmix_iend, ..Default::default() };
    let t0 = Instant::now();
    let profile = std::env::var_os("RAFF_BENCH_PROFILE").is_some();
    let mut t_step_us = 0u128;
    let mut t_force_us = 0u128;
    let mut t_rmsd_us = 0u128;
    let mut steps = Vec::new();
    let mut rmsds = Vec::new();
    let mut maxfs = Vec::new();
    let mut maxts = Vec::new();
    let mut nevals = Vec::new();
    let mut steps_to_t2 = None;
    let mut steps_to_t1 = None;
    let mut e_last = f64::INFINITY;
    let mut conv = false;
    let evals_per_outer = if orient_mode == OrientMode::Dynamic && solver == PosSolver::Projective { 3 } else { 2 };
    for st in 0..max_macro {
        let t_part = profile.then(Instant::now);
        let e = step_position_based(&mut s, topo, &cfg, &nb_off());
        if let Some(t) = t_part { t_step_us += t.elapsed().as_micros(); }
        e_last = e;
        let t_part = profile.then(Instant::now);
        let (max_f, max_t) = max_force(&s, topo);
        if let Some(t) = t_part { t_force_us += t.elapsed().as_micros(); }
        let t_part = profile.then(Instant::now);
        let r = if ref_pos.is_empty() { 0.0 } else { kabsch_rmsd(&s.pos, ref_pos) };
        if let Some(t) = t_part { t_rmsd_us += t.elapsed().as_micros(); }
        steps.push(st + 1);
        rmsds.push(r);
        maxfs.push(max_f);
        maxts.push(max_t);
        nevals.push((st + 1) * evals_per_outer);
        if steps_to_t2.is_none() && max_f < 0.1 && max_t < 0.1 { steps_to_t2 = Some(st + 1); }
        if steps_to_t1.is_none() && max_f < 1e-3 && max_t < 1e-3 { steps_to_t1 = Some(st + 1); conv = true; break; }
    }
    let t = t0.elapsed().as_micros();
    if profile {
        let n_wahba = if orient_mode == OrientMode::Adiabatic { steps.len() * (iters + 1) } else { 0 };
        let mut probe = s.clone();
        let tw = Instant::now();
        for _ in 0..n_wahba { solve_all_rotations(&mut probe, topo); }
        let t_wahba_us = tw.elapsed().as_micros();
        eprintln!("  [profile {:?}/{:?} dt={:.3} i={}] step={}us force_diag={}us rmsd={}us other={}us wahba_probe={}us/{}solves", solver, orient_mode, dt, iters,
            t_step_us, t_force_us, t_rmsd_us, t.saturating_sub(t_step_us + t_force_us + t_rmsd_us), t_wahba_us, n_wahba);
    }
    let label = if pd_inertia {
        format!("{:?}/{:?} dt={:.3} i={} PD+inertia+hb({},{})", solver, orient_mode, dt, iters, bmix_end, vel_reset as u8)
    } else {
        format!("{:?}/{:?} dt={:.3} i={} or={:.1}", solver, orient_mode, dt, iters, over_relax)
    };
    let n_inner = steps.len() * iters;
    let n_orient = if orient_mode == OrientMode::Adiabatic { 1 + steps.len() * (iters + 1) } else { steps.len() };
    Trace { label, solver: format!("{:?}", solver), distortion: String::new(), molecule: String::new(),
        steps, rmsd: rmsds, max_f: maxfs, max_t: maxts, n_evals: nevals, n_inner, n_orient,
        t_wall_us: t, steps_to_t2, steps_to_t1, final_e: e_last, converged: conv }
}

/// Relax with FIRE to moderate tolerance → reference geometry.
/// Target: |F| < 1e-3 eV/Å (1 meV/Å). Max 10k steps. Uses Dynamic orientation.
fn relax_reference(init: &RaffState, topo: &RaffTopology, max_steps: usize) -> RaffState {
    let mut s = init.clone();
    solve_all_rotations(&mut s, topo);
    let cfg = RaffConfig { orient_mode: OrientMode::Dynamic, dyn_mode: DynMode::ForceMD,
        pos_solver: PosSolver::PbdCompliance, dt: 0.001, cdamp: 0.0, rot_damp: 0.0, flim: 0.0,
        xpbd_iters: 16, xpbd_over_relax: 1.0, ..Default::default() };
    let n = s.natoms;
    let mut fapos = vec![Vec3d::new(0.,0.,0.); n];
    let mut tau = vec![Vec3d::new(0.,0.,0.); n];
    let mut fire = FireState::new(0.001, 0.01);
    for st in 0..max_steps {
        let (_, max_f, _) = step_fire(&mut s, topo, &cfg, &mut fire, &mut fapos, &mut tau, &nb_off());
        if max_f < 1e-3 { eprintln!("  [ref/FIRE] converged at step {} (|F|={:.2e})", st+1, max_f); break; }
    }
    s
}

/// Relax with FIRE, tracking per-step max|F| (primary) + RMSD vs reference (secondary).
/// Uses Dynamic orientation (smooth rotation — Adiabatic snaps pump energy into momentum).
fn trace_fire(init: &RaffState, ref_pos: &[Vec3d], topo: &RaffTopology, dt0: f64, dt_max: f64, max_steps: usize) -> Trace {
    let mut s = init.clone();
    solve_all_rotations(&mut s, topo);  // initial rotation solve only
    let cfg = RaffConfig { orient_mode: OrientMode::Dynamic, dyn_mode: DynMode::ForceMD,
        pos_solver: PosSolver::PbdCompliance, dt: dt0, cdamp: 0.0, rot_damp: 0.0, flim: 0.0,
        xpbd_iters: 16, xpbd_over_relax: 1.0, ..Default::default() };
    let n = s.natoms;
    let mut fapos = vec![Vec3d::new(0.,0.,0.); n];
    let mut tau = vec![Vec3d::new(0.,0.,0.); n];
    let mut fire = FireState::new(dt0, dt_max);
    let t0 = Instant::now();
    let mut steps = Vec::new();
    let mut rmsds = Vec::new();
    let mut maxfs = Vec::new();
    let mut maxts = Vec::new();
    let mut nevals = Vec::new();
    let mut steps_to_t2 = None;
    let mut steps_to_t1 = None;
    let mut e_last = f64::INFINITY;
    let mut conv = false;
    for st in 0..max_steps {
        let (e, max_f, max_t) = step_fire(&mut s, topo, &cfg, &mut fire, &mut fapos, &mut tau, &nb_off());
        e_last = e;
        let r = if ref_pos.is_empty() { 0.0 } else { kabsch_rmsd(&s.pos, ref_pos) };
        steps.push(st + 1);
        rmsds.push(r);
        maxfs.push(max_f);
        maxts.push(max_t);
        nevals.push(st + 1);
        if steps_to_t2.is_none() && max_f < 0.1 && max_t < 0.1 { steps_to_t2 = Some(st + 1); }
        if steps_to_t1.is_none() && max_f < 1e-3 && max_t < 1e-3 { steps_to_t1 = Some(st + 1); conv = true; break; }
    }
    let t = t0.elapsed().as_micros();
    Trace { label: format!("FIRE dt0={:.3} dtmax={:.2}", dt0, dt_max), solver: "FIRE".into(),
        distortion: String::new(), molecule: String::new(),
        n_orient: steps.len() + 1, steps, rmsd: rmsds, max_f: maxfs, max_t: maxts, n_evals: nevals, n_inner: 0,
        t_wall_us: t, steps_to_t2, steps_to_t1, final_e: e_last, converged: conv }
}

/// Write a trace's convergence curve to CSV.
fn write_csv(trace: &Trace, path: &str) {
    let mut f = File::create(path).expect(&format!("write_csv: cannot create {}", path));
    writeln!(f, "step,rmsd,max_f,max_t,n_evals").unwrap();
    for i in 0..trace.steps.len() {
        writeln!(f, "{},{:.6e},{:.6e},{:.6e},{}", trace.steps[i], trace.rmsd[i], trace.max_f[i], trace.max_t[i], trace.n_evals[i]).unwrap();
    }
}

/// Print a summary table row.
fn print_summary(traces: &[Trace]) {
    eprintln!("{:<52} {:>7} {:>7} {:>9} {:>9} {:>9} {:>9} {:>12} {:>5}",
        "solver/params", "to_T2", "to_T1", "n_force", "n_inner", "n_orient", "wall_us", "final_E", "conv");
    for t in traces {
        eprintln!("{:<52} {:>7} {:>7} {:>9} {:>9} {:>9} {:>9} {:>12.2e} {:>5}",
            t.label,
            t.steps_to_t2.map(|n| n.to_string()).unwrap_or("--".into()),
            t.steps_to_t1.map(|n| n.to_string()).unwrap_or("--".into()),
            t.n_evals.last().unwrap_or(&0), t.n_inner, t.n_orient, t.t_wall_us,
            t.final_e, if t.converged { "Y" } else { "N" });
    }
}

fn main() {
    let outdir = "debug/raff_bench";
    std::fs::create_dir_all(outdir).expect("create debug/raff_bench/");
    let mol_filter = std::env::var("RAFF_BENCH_MOLECULE").ok();
    let dist_filter = std::env::var("RAFF_BENCH_DISTORTION").ok();
    let solver_filter = std::env::var("RAFF_BENCH_SOLVER").ok();

    eprintln!("RAFF relaxation benchmark — convergence curves (§11.8)");
    eprintln!("Distortions: D1=random, D2=stretch(1.3x), D3a=dihedral(60°)");
    eprintln!("Targets: T2=rough(|F|<0.1eV/Å), T1=accurate(|F|<1e-3 eV/Å)  [force-based, DOF-independent]");
    eprintln!("Reference: force-MD relaxed geometry from same perturbed state (NOT input geometry)");
    eprintln!("Primary metric: max|F| (DOF-independent). RMSD is secondary (meaningless for free-DOF molecules).");
    eprintln!("Output: CSVs in {}/, plots via scripts/plot_raff_bench.py\n", outdir);

    // Molecules: (name, state, topo)
    let molecules: Vec<(&str, RaffState, RaffTopology)> = vec![
        ("CH4",       make_ch4().0,  make_ch4().1),
        ("water",     make_water().0, make_water().1),
        ("H2O2",      make_h2o2().0,  make_h2o2().1),
        ("tree20",    make_random_tree(20, 42).0,  make_random_tree(20, 42).1),
        ("tree100",   make_random_tree(100, 42).0, make_random_tree(100, 42).1),
    ];

    // Distortions: (name, function)
    let distortions: Vec<(&str, fn(&RaffState) -> RaffState)> = vec![
        ("D1_random",   |s| distort_random(s, 42)),
        ("D2_stretch",  |s| distort_stretch(s, 1.3)),
        ("D3a_dihedral",|s| distort_dihedral(s, 1.047)),
    ];

    // Solver configs: each entry is a closure that produces a Trace from (init, ref_pos, topo, max_steps)
    // We use a tagged enum to distinguish FIRE vs position-based vs damped-MD
    // PosPD = proper PD with outer inertia + heavy-ball momentum (ported from FireCore)
    enum SolverCfg {
        Fire(f64, f64), Inertial(f64), DampedMd(f64, f64),
        Pos(PosSolver, f64, usize, f64),  // legacy projection-only (no inertia)
        PosPD(PosSolver, f64, usize, f64, bool, f64, f64, usize, usize),  // adiabatic PD
        PosPDDynamic(PosSolver, f64, usize, f64, bool, f64, f64, usize, usize),  // torque/omega dynamic orientation
    }
    let solver_configs: Vec<(SolverCfg, &str)> = vec![
        // FIRE — momentum + adaptive dt + dot(v,F)<0 reset
        (SolverCfg::Fire(0.001, 0.02),  "FIRE"),
        // Inertial-reset — simple: full inertia, dot(v,F)<0 → v=0, constant dt. dt sweep.
        (SolverCfg::Inertial(0.005),  "Inertial-dt0.005"),
        (SolverCfg::Inertial(0.01),   "Inertial-dt0.01"),
        (SolverCfg::Inertial(0.02),   "Inertial-dt0.02"),
        // Damped Euler (old baseline — constant damping, no velocity reset)
        (SolverCfg::DampedMd(0.005, 0.95), "DampedMD"),
        // PBD-compliance or=1.9 — legacy projection-only (no inertia), dt=0.05
        (SolverCfg::Pos(PosSolver::PbdCompliance, 0.05, 16, 1.9), "PBD-or1.9"),
        // XPBD — legacy projection-only (no inertia), dt sweep
        (SolverCfg::Pos(PosSolver::Xpbd,          0.05, 16, 1.0), "XPBD-dt0.05"),
        (SolverCfg::Pos(PosSolver::Xpbd,          0.2,  16, 1.0), "XPBD-dt0.2"),
        // Projective — legacy projection-only (no inertia), dt sweep
        (SolverCfg::Pos(PosSolver::Projective,    0.05, 16, 1.0), "Projective-dt0.05"),
        (SolverCfg::Pos(PosSolver::Projective,    0.2,  16, 1.0), "Projective-dt0.2"),
        // === Proper PD: outer inertia + optional vel_reset + heavy-ball momentum ===
        // For i4, start at iteration 1 so iterations 1-2 actually use bmix=0.75; first/last remain unmixed.
        (SolverCfg::PosPD(PosSolver::Projective, 0.05, 4, 1.0, true,  0.75, 0.75, 1, 2), "PD-Proj-dt0.05-i4-reset"),
        (SolverCfg::PosPD(PosSolver::Projective, 0.1,  4, 1.0, true,  0.75, 0.75, 1, 2), "PD-Proj-dt0.1-i4-reset"),
        (SolverCfg::PosPD(PosSolver::Projective, 0.1,  4, 1.0, true,  0.0,  0.0,  1, 2), "PD-Proj-dt0.1-i4-nohb-reset"),
        (SolverCfg::PosPD(PosSolver::Projective, 0.1,  3, 1.0, true,  0.0,  0.0,  1, 2), "PD-Proj-dt0.1-i3-nohb-reset"),
        (SolverCfg::PosPD(PosSolver::Projective, 0.15, 3, 1.0, true,  0.0,  0.0,  1, 2), "PD-Proj-dt0.15-i3-nohb-reset"),
        (SolverCfg::PosPD(PosSolver::Projective, 0.2,  4, 1.0, true,  0.75, 0.75, 1, 2), "PD-Proj-dt0.2-i4-reset"),
        (SolverCfg::PosPD(PosSolver::Projective, 0.2,  4, 1.0, false, 0.75, 0.75, 1, 2), "PD-Proj-dt0.2-i4-free"),
        (SolverCfg::PosPD(PosSolver::Projective, 0.2,  4, 1.0, false, 0.0,  0.0,  1, 2), "PD-Proj-dt0.2-i4-nohb"),
        (SolverCfg::PosPD(PosSolver::Projective, 0.1,  2, 1.0, true,  0.0,  0.0,  1, 2), "PD-Proj-dt0.1-i2-reset"),
        (SolverCfg::PosPD(PosSolver::Projective, 0.1,  8, 1.0, true,  0.75, 0.75, 3, 4), "PD-Proj-dt0.1-i8-reset"),
        // XPBD with inertia + vel_reset (no heavy-ball — XPBD is GS, not Jacobi)
        (SolverCfg::PosPD(PosSolver::Xpbd, 0.1, 4, 1.0, true, 0.0, 0.0, 0, 0), "PD-XPBD-dt0.1-i4-reset"),
        (SolverCfg::PosPD(PosSolver::Xpbd, 0.2, 4, 1.0, true, 0.0, 0.0, 0, 0), "PD-XPBD-dt0.2-i4-reset"),
        // Projective with true torque/omega orientation dynamics; q is held fixed during each translational inner solve.
        (SolverCfg::PosPDDynamic(PosSolver::Projective, 0.005, 4, 1.0, true, 0.0, 0.0, 1, 2), "PD-ProjDyn-dt0.005-i4-reset"),
        (SolverCfg::PosPDDynamic(PosSolver::Projective, 0.01,  4, 1.0, true, 0.0, 0.0, 1, 2), "PD-ProjDyn-dt0.01-i4-reset"),
        (SolverCfg::PosPDDynamic(PosSolver::Projective, 0.02,  4, 1.0, true, 0.0, 0.0, 1, 2), "PD-ProjDyn-dt0.02-i4-reset"),
        (SolverCfg::PosPDDynamic(PosSolver::Projective, 0.05,  4, 1.0, true, 0.0, 0.0, 1, 2), "PD-ProjDyn-dt0.05-i4-reset"),
        (SolverCfg::PosPDDynamic(PosSolver::Projective, 0.1,   4, 1.0, true, 0.0, 0.0, 1, 2), "PD-ProjDyn-dt0.1-i4-reset"),
        (SolverCfg::PosPDDynamic(PosSolver::Projective, 0.1,   4, 1.0, true, 0.0, 0.0, 1, 2), "PD-ProjDyn-dt0.1-i4-reset"),
        (SolverCfg::PosPDDynamic(PosSolver::Projective, 0.15,  4, 1.0, true, 0.0, 0.0, 1, 2), "PD-ProjDyn-dt0.15-i4-reset"),
        (SolverCfg::PosPDDynamic(PosSolver::Projective, 0.2,   4, 1.0, true, 0.0, 0.0, 1, 2), "PD-ProjDyn-dt0.2-i4-reset"),
        (SolverCfg::PosPDDynamic(PosSolver::Projective, 0.1,   8, 1.0, true, 0.75, 0.75, 3, 4), "PD-ProjDyn-dt0.1-i8-reset"),
    ];

    let max_macro = 10_000;
    let max_steps = 10_000;
    let max_ref_steps = 10_000;

    for (mol_name, state, topo) in &molecules {
        if mol_filter.as_deref().is_some_and(|name| name != *mol_name) { continue; }
        for (dist_name, dist_fn) in &distortions {
            if dist_filter.as_deref().is_some_and(|name| name != *dist_name) { continue; }
            let init = dist_fn(state);
            eprintln!("\n=== {} / {} — computing reference ===", mol_name, dist_name);
            let ref_state = relax_reference(&init, topo, max_ref_steps);
            let ref_pos: Vec<Vec3d> = ref_state.pos.clone();
            let mut traces: Vec<Trace> = Vec::new();
            for (cfg, suffix) in &solver_configs {
                if solver_filter.as_deref().is_some_and(|name| name != *suffix) { continue; }
                let mut t = match cfg {
                    SolverCfg::Fire(dt0, dtmax) => trace_fire(&init, &ref_pos, topo, *dt0, *dtmax, max_steps),
                    SolverCfg::Inertial(dt) => trace_inertial(&init, &ref_pos, topo, *dt, max_steps),
                    SolverCfg::DampedMd(dt, cdamp) => trace_force_md(&init, &ref_pos, topo, *dt, *cdamp, max_steps),
                    SolverCfg::Pos(solver, dt, iters, or_) => trace_pos(&init, &ref_pos, topo, *solver, *dt, *iters, *or_, max_macro),
                    SolverCfg::PosPD(solver, dt, iters, or_, reset, bs, be, bis, bie) =>
                        trace_pos_ext(&init, &ref_pos, topo, *solver, *dt, *iters, *or_, max_macro,
                            OrientMode::Adiabatic, true, *reset, *bs, *be, *bis, *bie),
                    SolverCfg::PosPDDynamic(solver, dt, iters, or_, reset, bs, be, bis, bie) =>
                        trace_pos_ext(&init, &ref_pos, topo, *solver, *dt, *iters, *or_, max_macro,
                            OrientMode::Dynamic, true, *reset, *bs, *be, *bis, *bie),
                };
                t.distortion = dist_name.to_string();
                t.molecule = mol_name.to_string();
                t.solver = suffix.to_string();
                traces.push(t);
            }
            eprintln!("=== {} / {} — results ===", mol_name, dist_name);
            print_summary(&traces);
            for t in &traces {
                let fname = format!("{}/{}_{}_{}.csv", outdir, mol_name, dist_name, t.solver);
                write_csv(t, &fname);
            }
        }
    }

    eprintln!("\nDone. CSVs in {}/. Run: python3 {}/plot_raff_bench.py", outdir, outdir);
}
