// ==================== Molecule builders ====================

/// Build a molecule from positions + bonds. l0 = input bond length, ARAP ports → input is E=0 equilibrium.
fn make_molecule(apos: &[Vec3d], bonds: &[[i32; 2]], k_bond: f64) -> (RaffState, RaffTopology) {
    let n = apos.len();
    let mut topo = RaffTopology::new(n);
    topo.bond_params = bonds.iter().map(|b| {
        let d = apos[b[1] as usize] - apos[b[0] as usize];
        PortParam { k_p: k_bond / 2.0, l0: d.norm() }
    }).collect();
    topo.build_neighs_from_bonds(bonds);
    topo.set_port_geometry_from_reference(apos);
    let mut state = RaffState::new(n);
    state.set_positions(apos);
    (state, topo)
}

fn make_ch4() -> (RaffState, RaffTopology) {
    let s = 1.0 / 3.0_f64.sqrt();
    make_molecule(&[Vec3d::new(0.,0.,0.), Vec3d::new(s,s,s), Vec3d::new(s,-s,-s),
                    Vec3d::new(-s,s,-s), Vec3d::new(-s,-s,s)],
                  &[[0,1],[0,2],[0,3],[0,4]], 100.0)
}

fn make_water() -> (RaffState, RaffTopology) {
    make_molecule(&[Vec3d::new(0.,0.,0.), Vec3d::new(0.96,0.,0.), Vec3d::new(-0.24,0.93,0.)],
                  &[[0,1],[0,2]], 100.0)
}

/// H2O2 — hydrogen peroxide. 4 atoms, O-O bond + 2 O-H bonds.
/// Equilibrium HOOH dihedral ~111.5°. The port model does NOT constrain the dihedral
/// (it's a free DOF unless an explicit torsion term is added) — theory doc §11.8 D3a.
/// Geometry: O-O along z, H atoms in a twisted plane.
fn make_h2o2() -> (RaffState, RaffTopology) {
    let r_oo = 1.475;  // Å
    let r_oh = 0.965;  // Å
    let ang_hoo = 94.5_f64.to_radians();  // H-O-O angle
    let dih = 111.5_f64.to_radians();     // HOOH dihedral
    // O1 at origin, O2 along +z
    let o1 = Vec3d::new(0.0, 0.0, 0.0);
    let o2 = Vec3d::new(0.0, 0.0, r_oo);
    // H1: in xz plane, angle ang_hoo from O-O axis at O1
    let h1 = Vec3d::new(r_oh * ang_hoo.sin(), 0.0, -r_oh * ang_hoo.cos());
    // H2: twisted by dihedral around O-O axis from O2
    let h2 = Vec3d::new(r_oh * ang_hoo.sin() * dih.cos(), r_oh * ang_hoo.sin() * dih.sin(), r_oo + r_oh * ang_hoo.cos());
    make_molecule(&[o1, o2, h1, h2], &[[0,1],[0,2],[1,3]], 100.0)
}

/// Deterministic pseudo-random tree of `n` atoms (degree ≤ 4 per node).
fn make_random_tree(n: usize, seed: u64) -> (RaffState, RaffTopology) {
    let mut apos = vec![Vec3d::new(0.0,0.0,0.0); n];
    let mut bonds: Vec<[i32;2]> = Vec::with_capacity(n-1);
    let mut degree = vec![0u32; n];
    let mut rng = seed;
    let mut next = || { rng = rng.wrapping_mul(6364136223846793005).wrapping_add(1442695040888963407); (rng >> 33) as f64 / (1u64 << 31) as f64 };
    for k in 1..n {
        let mut parent = (next() * k as f64) as usize;
        for _ in 0..8 { if degree[parent] < 4 { break; } parent = (next() * k as f64) as usize; }
        if degree[parent] >= 4 { parent = (0..k).find(|&p| degree[p] < 4).unwrap_or(parent); }
        assert!(degree[parent] < 4, "make_random_tree: no open parent for atom {}", k);
        let mut d = Vec3d::new(next()*2.0-1.0, next()*2.0-1.0, next()*2.0-1.0);
        let nrm = d.norm();
        if nrm < 1e-6 { d = Vec3d::new(1.0,0.0,0.0); } else { d = d * (1.0/nrm); }
        apos[k] = apos[parent] + d * 1.0;
        bonds.push([parent as i32, k as i32]);
        degree[parent] += 1; degree[k] += 1;
    }
    make_molecule(&apos, &bonds, 100.0)
}

// ==================== Distortion types (§11.8) ====================

/// D1 — Random displacement (high-frequency white noise).
/// Each atom gets an independent random displacement of magnitude ~0.15 Å.
fn distort_random(state: &RaffState, seed: u64) -> RaffState {
    let mut s = state.clone();
    let mut rng = seed;
    let mut next = || { rng = rng.wrapping_mul(6364136223846793005).wrapping_add(1); (rng >> 33) as f64 / (1u64 << 31) as f64 };
    for i in 0..s.natoms {
        s.pos[i] = s.pos[i] + Vec3d::new((next()*2.0-1.0)*0.15, (next()*2.0-1.0)*0.15, (next()*2.0-1.0)*0.15);
        s.vel[i] = Vec3d::new(0.,0.,0.); s.omega[i] = Vec3d::new(0.,0.,0.);
    }
    s
}

/// D2 — Uniaxial stretch along the PCA long axis (low-frequency, pathological).
/// Scale positions along the principal axis by `factor` (1.3 = 30% stretch).
/// This excites the lowest acoustic mode — the long-narrow-valley / Rosenbrock pathology.
fn distort_stretch(state: &RaffState, factor: f64) -> RaffState {
    let n = state.natoms;
    // Centroid
    let mut c = Vec3d::new(0.,0.,0.);
    for i in 0..n { c.add(state.pos[i]); }
    c.mul(1.0 / n as f64);
    // Covariance matrix (3x3) of centered positions
    let mut cov = [[0.0f64; 3]; 3];
    for i in 0..n {
        let p = state.pos[i] - c;
        for a in 0..3 { for b in 0..3 { cov[a][b] += p[a] * p[b]; } }
    }
    // Power iteration for dominant eigenvector (principal axis)
    let mut v = [1.0f64, 0.0, 0.0];
    for _ in 0..100 {
        let mut w = [0.0f64; 3];
        for a in 0..3 { for b in 0..3 { w[a] += cov[a][b] * v[b]; } }
        let nrm = (w[0]*w[0] + w[1]*w[1] + w[2]*w[2]).sqrt();
        if nrm < 1e-30 { break; }
        for a in 0..3 { v[a] = w[a] / nrm; }
    }
    // Stretch: scale the component along principal axis by `factor`
    let mut s = state.clone();
    for i in 0..n {
        let p = state.pos[i] - c;
        let proj = v[0]*p.x + v[1]*p.y + v[2]*p.z;
        let stretched = proj * factor;
        let delta = (stretched - proj);
        s.pos[i] = state.pos[i] + Vec3d::new(v[0]*delta, v[1]*delta, v[2]*delta);
        s.vel[i] = Vec3d::new(0.,0.,0.); s.omega[i] = Vec3d::new(0.,0.,0.);
    }
    s
}

/// D3a — Dihedral perturbation. Rotate the second half of the molecule around
/// the bond axis by `angle` radians. For H2O2: rotate H2+O2 around the O-O axis.
/// For chains: rotate atoms after the middle bond around that bond axis.
fn distort_dihedral(state: &RaffState, angle: f64) -> RaffState {
    let n = state.natoms;
    if n < 4 { return distort_random(state, 42); }  // dihedral needs ≥4 atoms
    // Find the "middle" bond: bond between atom n/2-1 and n/2 (heuristic for H2O2: bond 0-1 = O-O)
    // For H2O2 (4 atoms, bonds [0,1],[0,2],[1,3]): middle bond = [0,1]
    // For chain4: middle bond = [1,2]
    // We rotate atoms on one side of this bond.
    // Simple heuristic: bond index = n/2 - 1, rotate atoms with index > mid around axis pos[a]→pos[b]
    let mid = if n == 4 { 0 } else { n / 2 - 1 };
    let a = mid;
    let b = mid + 1;
    let axis = state.pos[b] - state.pos[a];
    let axis_len = axis.norm();
    if axis_len < 1e-10 { return distort_random(state, 42); }
    let ax = axis * (1.0 / axis_len);
    // Rotate atoms with index > b around axis through pos[b]
    let cos = angle.cos();
    let sin = angle.sin();
    let mut s = state.clone();
    for i in 0..n {
        if i > b {
            let p = state.pos[i] - state.pos[b];
            // Rodrigues rotation around unit axis ax by angle
            let dot = p.x*ax.x + p.y*ax.y + p.z*ax.z;
            let cross = Vec3d::cross(ax, p);
            let rotated = p * cos + cross * sin + ax * (dot * (1.0 - cos));
            s.pos[i] = state.pos[b] + rotated;
        }
        s.vel[i] = Vec3d::new(0.,0.,0.); s.omega[i] = Vec3d::new(0.,0.,0.);
    }
    s
}

// ==================== Convergence tracking ====================

/// Compute max|F| (translational force) + max|τ| (torque) for a state.
fn max_force(state: &RaffState, topo: &RaffTopology) -> (f64, f64) {
    let n = state.natoms;
    let mut fapos = vec![Vec3d::new(0.,0.,0.); n];
    let mut tau = vec![Vec3d::new(0.,0.,0.); n];
    eval_port_forces(state, topo, &mut fapos, &mut tau);
    let max_f = fapos.iter().map(|f| f.norm()).fold(0.0f64, f64::max);
    let max_t = tau.iter().map(|t| t.norm()).fold(0.0f64, f64::max);
    (max_f, max_t)
}

struct Trace {
    label: String,
    solver: String,
    distortion: String,
    molecule: String,
    steps: Vec<usize>,       // macrostep index
    rmsd: Vec<f64>,          // Kabsch RMSD vs force-MD reference (may be meaningless for free-DOF molecules)
    max_f: Vec<f64>,         // max|F| [eV/Å]
    max_t: Vec<f64>,         // max|τ| [eV]; convergence requires both force and torque thresholds
    n_evals: Vec<usize>,     // cumulative port-force evaluations, including convergence diagnostics
    n_inner: usize,          // total local/global or constraint sweeps
    n_orient: usize,         // total adiabatic solves or dynamic rotational updates
    t_wall_us: u128,
    steps_to_t2: Option<usize>,  // rough: |F|<0.1 eV/Å (force-based, DOF-independent)
    steps_to_t1: Option<usize>,  // accurate: |F|<1e-3 eV/Å
    final_e: f64,
    converged: bool,
}

/// Relax with force-MD, tracking per-step max|F| (primary) + RMSD vs reference (secondary).
/// Convergence is detected by force threshold (DOF-independent), not RMSD.
fn trace_force_md(init: &RaffState, ref_pos: &[Vec3d], topo: &RaffTopology, dt: f64, cdamp: f64, max_steps: usize) -> Trace {
    let mut s = init.clone();
    solve_all_rotations(&mut s, topo);
    let cfg = RaffConfig { orient_mode: OrientMode::Adiabatic, dyn_mode: DynMode::ForceMD,
        pos_solver: PosSolver::PbdCompliance, dt, cdamp, rot_damp: cdamp, flim: 0.0,
        xpbd_iters: 16, xpbd_over_relax: 1.0, ..Default::default() };
    let n = s.natoms;
    let mut fapos = vec![Vec3d::new(0.,0.,0.); n];
    let mut tau = vec![Vec3d::new(0.,0.,0.); n];
    let t0 = Instant::now();
    let mut steps = Vec::new();
    let mut rmsds = Vec::new();
    let mut maxfs = Vec::new();
    let mut maxts = Vec::new();
    let mut nevals = Vec::new();
    let mut steps_to_t2 = None;
    let mut steps_to_t1 = None;
    let mut e_last = f64::INFINITY;
    let mut conv = false;
    for st in 0..max_steps {
        solve_all_rotations(&mut s, topo);
        let (e, max_f, max_t) = step_force_md(&mut s, topo, &cfg, &mut fapos, &mut tau, &nb_off());
        e_last = e;
        let r = if ref_pos.is_empty() { 0.0 } else { kabsch_rmsd(&s.pos, ref_pos) };
        steps.push(st + 1);
        rmsds.push(r);
        maxfs.push(max_f);
        maxts.push(max_t);
        nevals.push(st + 1);
        if steps_to_t2.is_none() && max_f < 0.1 && max_t < 0.1 { steps_to_t2 = Some(st + 1); }
        if steps_to_t1.is_none() && max_f < 1e-3 && max_t < 1e-3 { steps_to_t1 = Some(st + 1); conv = true; break; }
    }
    let t = t0.elapsed().as_micros();
    Trace { label: format!("ForceMD dt={:.3}", dt), solver: "ForceMD".into(), distortion: String::new(), molecule: String::new(),
        n_orient: steps.len() + 1, steps, rmsd: rmsds, max_f: maxfs, max_t: maxts, n_evals: nevals, n_inner: 0,
        t_wall_us: t, steps_to_t2, steps_to_t1, final_e: e_last, converged: conv }
}

